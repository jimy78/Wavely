export default async function handler(req, res) {
  // Pas d'en-têtes CORS : l'API n'est appelée qu'en same-origin par le front.
  // Les navigateurs tiers sont ainsi bloqués par défaut.
  if (req.method === "OPTIONS") return res.status(204).end();
  if (req.method !== "POST") return res.status(405).json({ error: "Method not allowed" });

  // Garde-fou optionnel contre l'usage non autorisé du proxy : si
  // DRH_ACCESS_CODE est défini côté Vercel, le front doit fournir le code.
  const accessCode = process.env.DRH_ACCESS_CODE;
  if (accessCode && req.headers["x-access-code"] !== accessCode) {
    return res.status(401).json({ error: "Unauthorized", detail: "Code d'accès requis" });
  }

  const { messages } = req.body;
  if (!Array.isArray(messages) || messages.length === 0) {
    return res.status(400).json({ error: "Missing messages" });
  }

  // Contexte borné pour limiter le coût par requête
  const history = messages.slice(-12).map((m) => ({
    role: m.role === "assistant" ? "assistant" : "user",
    content: String(m.content || "").slice(0, 6000),
  }));

  try {
    const response = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-api-key": process.env.ANTHROPIC_API_KEY,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify({
        model: "claude-opus-5",
        max_tokens: 8000,
        output_config: { effort: "medium" },
        system: [{ type: "text", text: SYSTEM_DRH, cache_control: { type: "ephemeral" } }],
        messages: history,
      }),
    });

    const data = await response.json();
    if (!response.ok) {
      return res.status(response.status).json({ error: "AI error", detail: data.error?.message });
    }
    if (data.stop_reason === "refusal") {
      return res.status(200).json({
        reply:
          "Je ne peux pas traiter cette demande. Reformulez-la ou précisez le contexte RH, et je vous aiderai volontiers.",
      });
    }

    const reply = (data.content || [])
      .filter((b) => b.type === "text")
      .map((b) => b.text)
      .join("\n");
    if (!reply) return res.status(500).json({ error: "No response from AI" });

    res.status(200).json({ reply });
  } catch (e) {
    res.status(500).json({ error: "DRH agent failed", detail: e.message });
  }
}
